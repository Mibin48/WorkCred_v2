import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const envPath = path.resolve(__dirname, '../.env');

if (fs.existsSync(envPath)) {
  console.log('backend/.env already exists. Setup will not overwrite it.');
  process.exit(0);
}

const jwtAccessSecret = crypto.randomBytes(32).toString('hex');
const jwtRefreshSecret = crypto.randomBytes(32).toString('hex');
const codesEncKey = crypto.randomBytes(32).toString('base64');

const envContent = `# WorkCred Backend Environment Configuration (Generated by setup)
NODE_ENV=development
PORT=4000
MONGODB_URI=mongodb://localhost:27017/workcred
FRONTEND_ORIGINS=http://localhost:3000
JWT_ACCESS_SECRET=${jwtAccessSecret}
JWT_REFRESH_SECRET=${jwtRefreshSecret}
CODES_ENC_KEY=${codesEncKey}
LOG_LEVEL=info
TRUST_PROXY=false
RATE_LIMIT_ENABLED=true
`;

fs.writeFileSync(envPath, envContent, { encoding: 'utf8' });
console.log('Created backend/.env with fresh random secrets.');
